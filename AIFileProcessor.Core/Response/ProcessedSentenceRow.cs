namespace AIFileProcessor.Response
{
    using System;
    using System.Collections.Generic;
    using System.Text;
    using System.Text.Json.Serialization;
    using AIFileProcessor.Extensions;

    /// <summary>
    /// The processed sentence row after the AI has generated the output. This class maps to the JSON structure of each row in the processed sentences output.
    /// </summary>
    public class ProcessedSentenceRow
    {
        /// <summary>
        /// Gets or sets the unique Id generated by the client for each sentence after the API call, which is used for tracking and reordering purposes.
        /// </summary>
        [JsonPropertyName("I")]
        public string Id { get; set; } = string.Empty;

        /// <summary>
        /// Gets or sets the space separated list of the original sentence's Chinese characters broken down into word segments, with punctuation sanitized to a standard form. The sanitization is handled by the custom JSON converter 'ChinesePunctuationSanitizingConverter' which ensures that all punctuation is normalized to a consistent set of characters for easier processing and comparison.
        /// </summary>
        [JsonConverter(typeof(ChinesePunctuationSanitizingConverter))]
        [JsonPropertyName("C")]
        public string Chinese { get; set; } = string.Empty;

        /// <summary>
        /// Gets or sets the pinyin (romanized) representation of the text. In cases such as ¥100 this will be 100 ¥ to reflect the actual spoken order.
        /// </summary>
        /// <remarks>Serialized as "P" in JSON. Defaults to an empty string.</remarks>
        [JsonPropertyName("P")]
        public string Pinyin { get; set; } = string.Empty;

        /// <summary>
        /// Gets or sets the breakdown of the sentence into its constituent parts.
        /// </summary>
        /// <remarks>Serialized as "B" in JSON. Defaults to an empty string.</remarks>
        [JsonPropertyName("B")]
        [JsonConverter(typeof(PipeDelimitedBreakdownConverter))]
        public List<BreakdownEntry> Breakdown { get; set; } = [];

        /// <summary>
        /// Sets the pipe-delimited reordering metadata (mapped from 'R').
        /// Format matches: VisualString|Index,Index||NextEvent OR 'N/A'.
        /// </summary>
        [JsonPropertyName("R")]
        public string R
        {
            set => AudioReordering = ParseAudioReordering(value);
        }

        // Initialize with an empty list instead of [new()] to avoid a phantom
        // AudioReorder entry (VisualString="", StartIndex=-1, EndIndex=-1) when the
        // "R" property is never set during deserialization.
        [JsonIgnore]
        public List<AudioReorder> AudioReordering { get; set; } = [];

        /// <summary>
        /// Gets or sets the English translation of the sentence.
        /// </summary>
        /// <remarks>Serialized as "E" in JSON. Defaults to an empty string.</remarks>
        [JsonPropertyName("E")]
        public string English { get; set; } = string.Empty;

        /// <summary>
        /// Gets or sets the length of the sentence.
        /// </summary>
        /// <remarks>Serialized as "L" in JSON. Defaults to an empty string.</remarks>
        [JsonPropertyName("L")]
        public string Length { get; set; } = string.Empty;

        /// <summary>
        /// Fills in the Id for the sentence.
        /// </summary>
        /// <param name="prefix">The prefix to be used to create the Id.</param>
        /// <param name="sequentialValue">The integer portion of the Id.</param>
        /// <param name="idPad">The padding to be used to format the sequentialValue.</param>
        public void InitializeId(string prefix, int sequentialValue, int idPad)
        {
            Id = $"{prefix.Trim()}{sequentialValue.ToString("D" + idPad)}";
        }

        /// <summary>
        /// Reconstructs the row's pinyin and updates its breakdown entries based on the transformed sandhi results.
        /// </summary>
        /// <param name="transformed">The transformed sandhi results for this row.</param>
        /// <param name="entryBoundaries">The start index and length boundary tuples of each breakdown entry within the syllable stream.</param>
        public void ApplySandhiResults(IReadOnlyList<SandhiResult> transformed, IReadOnlyList<(int Start, int Count)> entryBoundaries)
        {
            if (Breakdown == null || Breakdown.Count == 0)
            {
                return;
            }

            var sentencePinyinParts = new List<string>();
            for (int e = 0; e < Breakdown.Count; e++)
            {
                var (start, count) = entryBoundaries[e];
                var entrySyllables = new StringBuilder();
                var entryNotes = new List<string>();

                for (int i = 0; i < count; i++)
                {
                    if (i > 0)
                    {
                        entrySyllables.Append(' ');
                    }

                    var result = transformed[start + i];
                    entrySyllables.Append(result.Transformed);

                    if (result.Note != null)
                    {
                        entryNotes.Add(result.Note);
                    }
                }

                string transformedPinyin = entrySyllables.ToString();
                Breakdown[e].Pinyin = transformedPinyin;
                sentencePinyinParts.Add(transformedPinyin);

                // Append sandhi notes to the existing Note field
                if (entryNotes.Count > 0)
                {
                    string sandhiNote = string.Join(" ", entryNotes);
                    if (!string.IsNullOrEmpty(Breakdown[e].Note))
                    {
                        Breakdown[e].Note = Breakdown[e].Note + " " + sandhiNote;
                    }
                    else
                    {
                        Breakdown[e].Note = sandhiNote;
                    }
                }
            }

            // Reconstruct sentence-level pinyin from the transformed breakdown pinyin.
            // Avoid inserting a space before punctuation (common expectation in
            // romanization output).
            var sb = new StringBuilder();
            for (int i = 0; i < sentencePinyinParts.Count; i++)
            {
                string part = sentencePinyinParts[i];
                string pos = Breakdown?[i].PartOfSpeech ?? string.Empty;

                bool isPunctuation = string.Equals(pos, "Punctuation", System.StringComparison.OrdinalIgnoreCase)
                    || System.Linq.Enumerable.All(part, ch => char.IsPunctuation(ch));

                if (sb.Length == 0)
                {
                    sb.Append(part);
                }
                else if (isPunctuation)
                {
                    // Append punctuation directly with no leading space
                    sb.Append(part);
                }
                else
                {
                    sb.Append(' ').Append(part);
                }
            }

            Pinyin = sb.ToString();
        }

        private static List<AudioReorder> ParseAudioReordering(string rValue)
        {
            var reorders = new List<AudioReorder>();

            if (string.IsNullOrWhiteSpace(rValue) || rValue.Trim().Equals("N/A", StringComparison.OrdinalIgnoreCase))
            {
                return reorders;
            }

            var segments = rValue.Split("||", StringSplitOptions.RemoveEmptyEntries);
            foreach (var segment in segments)
            {
                var parts = segment.Split('|');
                if (parts.Length < 2)
                {
                    continue;
                }

                var visualString = parts[0].Trim();
                var indicesPart = parts[1].Trim();

                int startIndex = -1;
                int endIndex = -1;

                var indices = indicesPart.Split(',', StringSplitOptions.RemoveEmptyEntries);
                if (indices.Length > 0 && int.TryParse(indices[0].Trim(), out var parsedStart))
                {
                    startIndex = parsedStart;
                }

                if (indices.Length > 1 && int.TryParse(indices[1].Trim(), out var parsedEnd))
                {
                    endIndex = parsedEnd;
                }

                reorders.Add(new AudioReorder
                {
                    VisualString = visualString,
                    StartIndex = startIndex,
                    EndIndex = endIndex
                });
            }

            return reorders;
        }
    }
}
